#pragma once                               
#include <iostream>
#include <string>

using namespace std;

class Point {
private:
    // Декартові координати точки (закриті від зовнішнього втручання)
    double x;                               // координата по осі X
    double y;                               // координата по осі Y

public:
    // ================= КОНСТРУКТОРИ =================
    Point();                                // Без параметрів (створює точку 0,0)
    Point(double x, double y);              // З параметрами (ініціалізує заданими числами)
    Point(const Point& other);              // Копіювання (створює точну копію існуючої точки)
    ~Point();                               // Деструктор (очищає об'єкт при його знищенні)

    // ================= МЕТОДИ ДОСТУПУ =================
    double getX() const;                    // const гарантує, що метод тільки читає і не змінює об'єкт
    void setX(double x);                    // Сетер для безпечного запису X (з перевіркою)
    double getY() const;                    // const гарантує безпечне читання Y
    void setY(double y);                    // Сетер для безпечного запису Y

    // ================= БІЗНЕС-ЛОГІКА (Варіант 15) =================
    void toPolar(double& r, double& phi) const; // Повертає 2 значення одночасно через посилання (&)
    double distanceToOrigin() const;            // Рахує відстань за теоремою Піфагора

    // ================= ПЕРЕВАНТАЖЕННЯ ОПЕРАЦІЙ (Методи класу) =================
    Point& operator=(const Point& other);   // Повертає посилання (&) для ланцюжків присвоєння (a = b = c)
    operator string() const;                // Оператор приведення типу (об'єкт -> текст)

    // Унарні операції (інкремент/декремент)
    Point& operator++();                    // Префіксний (++p). Змінює X і повертає змінений об'єкт
    Point& operator--();                    // Префіксний (--p). Змінює X і повертає змінений об'єкт
    Point operator++(int);                  // Постфіксний (p++). int - це фіктивний параметр-маркер! Змінює Y.
    Point operator--(int);                  // Постфіксний (p--). Повертає КОПІЮ старого стану, а потім змінює Y.

    // ================= ДРУЖНІ ФУНКЦІЇ (Бінарні операції) =================
    // friend дозволяє зовнішнім функціям напряму читати приватні поля x та y
    friend bool operator==(const Point& a, const Point& b);
    friend bool operator!=(const Point& a, const Point& b);

    // Потокове введення/виведення (повертають потік, щоб працювало cout << a << b)
    friend ostream& operator<<(ostream& out, const Point& p); // out - це потік виводу (наприклад, cout)
    friend istream& operator>>(istream& in, Point& p);        // in - це потік вводу (наприклад, cin)
};